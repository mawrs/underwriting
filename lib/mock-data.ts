function doc(partial: {
  id: string;
  name: string;
  kind: DocumentKind;
  typeLabel: string;
  description: string;
  fileName: string;
  uploadedAt: string;
  sourceStatus?: string;
  reviewStatus?: DocumentStatus;
}): UploadedDocument {
  return {
    sourceStatus: "",
    reviewStatus: "pending",
    reviewedAt: null,
    note: "",
    ...partial,
  };
}

function liability(partial: Omit<Liability, "confirmed" | "selected" | "payoffType"> & Partial<Liability>): Liability {
  return {
    selected: false,
    payoffType: "full",
    confirmed: false,
    ...partial,
  };
}

function tradesFromLiabilities(items: Liability[]): DebtTrade[] {
  return items.map((item) => ({
    id: item.id,
    tradeType: item.category === "EDUCATIONAL" ? "Student Loan" : item.category,
    accountNumber: item.accountNumber,
    lender: item.lender,
    category: item.category,
    accountType: item.accountType,
    highCredit: item.highCredit,
    balance: item.balance,
    payment: item.payment,
    includeInDti: item.payment > 0,
  }));
}

