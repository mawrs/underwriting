function lightApplication(input: {
  id: string;
  name: string;
  recordType: Application["recordType"];
  amount: number;
  priority: number;
  difficulty: Application["difficulty"];
  referrer: string;
  underwriter: string;
  owner: string;
  applicationDate: string;
  hardCreditDate: string;
  preReviewAt: string;
  status?: WorkflowStatus;
  email: string;
  state: string;
  hasCosigner?: boolean;
}): Application {
  const cloneLiabilities = madelineLiabilities.map((item, index) => ({
    ...item,
    id: `${input.id}-${item.id}`,
    selected: index < 3,
    confirmed: false,
    adjBalance: Math.round(item.adjBalance * (input.amount / 67359.71) * 100) / 100,
  }));

  return {
    ...madeline,
    id: input.id,
    opportunityName: `${input.name}-${input.id}`,
    recordType: input.recordType,
    amount: input.amount,
    applicationDate: input.applicationDate,
    hardCreditDate: input.hardCreditDate,
    preReviewAt: input.preReviewAt,
    priority: input.priority,
    difficulty: input.difficulty,
    referrer: input.referrer,
    underwriter: input.underwriter,
    owner: input.owner,
    status: input.status ?? "pre-review",
    cosigner: input.hasCosigner ? sampleCosigner : null,
    borrower: {
      ...madeline.borrower,
      fullName: input.name,
      email: input.email,
      state: input.state,
    },
    liabilities: cloneLiabilities,
    debtTrades: tradesFromLiabilities(cloneLiabilities),
    documents: madeline.documents.map((item) => ({
      ...item,
      id: `${input.id}-${item.id}`,
      reviewStatus: "pending" as DocumentStatus,
      reviewedAt: null,
      note: "",
    })),
    notes: emptyNotes(),
    decision: "",
    seniorNotes: "",
    seniorDecision: "",
    submittedAt: null,
    returnedAt: null,
    approvedAt: null,
    primarySnapshot: null,
    lastSavedAt: null,
  };
}

